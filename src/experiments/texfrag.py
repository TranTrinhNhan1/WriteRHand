"""LaTeX fragments for the report, generated from ``results/`` (no hand-typed numbers).

Everything is written to ``report/generated/``:

* ``numbers.tex``      -- ``\\newcommand`` macros for every figure quoted in the prose;
* ``hardware.tex``     -- one-line description of the machine used for timings;
* ``ntests.tex``       -- number of automatic tests (collected with pytest);
* ``export_check.tex`` -- ONNX/JSON parity summary from ``artifacts/bundle/manifest.json``;
* ``augmentation.tex`` -- table of the augmentation study;
* ``confusions.tex``   -- the most frequent confusions of each model;
* ``sweeps.tex``       -- what each hyper-parameter sweep found (best/worst validation accuracy).
"""

import json
import re
import subprocess
import sys
from pathlib import Path

from src.experiments.report import ORDER, TITLE, load_all, sweep_points, top_confusions
from src.utils.paths import ARTIFACTS_DIR, ROOT

PREFIX = {"naive_bayes": "NB", "softmax": "SM", "mlp": "MLP", "adaboost": "ADA", "cnn": "CNN"}
_ESC = str.maketrans({"_": r"\_", "%": r"\%", "&": r"\&", "#": r"\#"})


def _tex(s):
    return str(s).translate(_ESC)


def _pct(x, nd=2):
    return f"{100 * x:.{nd}f}"


def _macro(name, value):
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def write_numbers(data, out_dir):
    lines = ["% generated by src/experiments/texfrag.py -- do not edit"]
    for mid in ORDER:
        p, d = PREFIX[mid], data[mid]
        f, sk, tu = d["final"], d["sklearn"], d["tuning"]
        if f:
            s = f["splits"]
            for split, tag in (("train", "Train"), ("val", "Val"), ("test", "Test")):
                lines.append(_macro(f"acc{tag}{p}", _pct(s[split]["accuracy"])))
            lines.append(_macro(f"fone{p}", _pct(s["test"]["f1_macro"])))
            lines.append(_macro(f"prec{p}", _pct(s["test"]["precision_macro"])))
            lines.append(_macro(f"rec{p}", _pct(s["test"]["recall_macro"])))
            lines.append(_macro(f"errors{p}", str(round(10_000 * (1 - s["test"]["accuracy"])))))
            lines.append(_macro(f"fit{p}", f"{f['train_time_sec']:.1f}"))
            lines.append(_macro(f"pred{p}", f"{s['test']['predict_time_sec']:.3f}"))
            lines.append(_macro(f"lat{p}", f"{f['latency_ms_single_sample']:.3f}"))
            lines.append(_macro(f"gap{p}", _pct(s["train"]["accuracy"] - s["test"]["accuracy"])))
        if sk:
            lines.append(_macro(f"accTestSk{p}", _pct(sk["splits"]["test"]["accuracy"])))
            lines.append(_macro(f"fitSk{p}", f"{sk['train_time_sec']:.1f}"))
            if f:
                diff = abs(f["splits"]["test"]["accuracy"] - sk["splits"]["test"]["accuracy"])
                lines.append(_macro(f"diffSk{p}", _pct(diff)))
        if tu:
            lines.append(_macro(f"ntrials{p}", str(tu["n_trials"])))
            lines.append(_macro(f"bestVal{p}", _pct(tu["best_val_acc"])))
    meta = next((d["final"]["dataset"] for d in data.values() if d["final"]), None)
    if meta:
        lines.append(_macro("splitFingerprint", meta["split_fingerprint"]))
        lines.append(_macro("pixMean", f"{meta['mean']:.4f}"))
        lines.append(_macro("pixStd", f"{meta['std']:.4f}"))
    (out_dir / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def mcnemar(results_dir, a="MLP", b="AdaBoostSAMME"):
    """Exact McNemar test between two models' test predictions (paired, same 10 000 images)."""
    import numpy as np
    from scipy.stats import binomtest

    from src.preprocessing.preprocess import load_dataset

    rd = Path(results_dir) / "final"
    if not (rd / f"{a}_predictions.npz").is_file() or not (rd / f"{b}_predictions.npz").is_file():
        return None
    y = load_dataset()[0]["y_test"]
    pa = np.load(rd / f"{a}_predictions.npz")["test"] == y
    pb = np.load(rd / f"{b}_predictions.npz")["test"] == y
    only_a, only_b = int((pa & ~pb).sum()), int((~pa & pb).sum())
    n = only_a + only_b
    p = binomtest(only_a, n, 0.5).pvalue if n else 1.0
    return {"only_a": only_a, "only_b": only_b, "p": float(p)}


def write_mcnemar(results_dir, out_dir):
    r = mcnemar(results_dir)
    lines = []
    if r:
        p = r["p"]
        ptxt = (
            f"{p:.2g}".replace("e-0", "e-").replace("e-", r"\times10^{-") + "}"
            if "e" in f"{p:.2g}"
            else f"{p:.3f}"
        )
        lines += [
            _macro("mcOnlyMLP", str(r["only_a"])),
            _macro("mcOnlyADA", str(r["only_b"])),
            _macro("mcP", f"${ptxt}$"),
        ]
    (out_dir / "mcnemar.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_hardware(data, out_dir):
    hw = next((d["final"]["hardware"] for d in data.values() if d["final"]), None)
    if hw:
        cpu = re.sub(r"\(R\)|\(TM\)", "", hw["cpu"]).replace("  ", " ").strip()
        txt = (
            f"{_tex(cpu)}, {hw['logical_cores']} luồng logic, PyTorch {hw['torch_threads']} luồng, "
            f"Python {_tex(hw['python'])}"
        )
    else:
        txt = "chưa có thông tin phần cứng"
    (out_dir / "hardware.tex").write_text(txt + "%\n", encoding="utf-8")


def write_ntests(out_dir):
    n = None
    try:
        out = subprocess.run(
            [sys.executable, "-m", "pytest", "--collect-only", "-q"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=300,
            check=False,
        ).stdout
        m = re.search(r"(\d+) tests? collected", out) or re.search(r"^(\d+)/\d+ tests", out, re.M)
        if m:
            n = int(m.group(1))
        else:
            n = sum(1 for ln in out.splitlines() if "::" in ln) or None
    except Exception:
        n = None
    (out_dir / "ntests.tex").write_text((str(n) if n else "nhiều") + "%\n", encoding="utf-8")


def write_export_check(out_dir, artifacts_dir=ARTIFACTS_DIR):
    path = Path(artifacts_dir) / "bundle" / "manifest.json"
    if not path.is_file():
        txt = "chưa chạy bước xuất mô hình trong lần biên dịch này"
    else:
        man = json.loads(path.read_text(encoding="utf-8"))
        man = man["datasets"]["mnist"]  # the sentence in the report is about MNIST
        parts = []
        for mid in ORDER:
            m = man["models"].get(mid)
            if not m:
                continue
            v = m["validation"]
            parts.append(
                f"{_tex(TITLE[mid])}: sai lệch xác suất lớn nhất ${v['max_abs_prob_diff']:.1e}$, "
                f"trùng nhãn {_pct(v['argmax_agreement'])}\\% trên {v['n_checked']:,} ảnh".replace(
                    ",", "\\,"
                )
            )
        txt = "; ".join(parts)
    (out_dir / "export_check.tex").write_text(txt + "%\n", encoding="utf-8")


AUG_NAME = {
    "baseline": "Không tăng cường",
    "rotation": "Xoay",
    "translation": "Dịch chuyển",
    "scaling": "Co giãn",
    "gaussian_noise": "Nhiễu Gauss",
    "salt_pepper": "Nhiễu muối tiêu",
    "geometric": "Hình học (xoay, dịch, co giãn)",
    "all": "Cả năm phép",
}


def write_augmentation(results_dir, out_dir):
    """One table per model (``augmentation_mlp.tex``, ``augmentation_cnn.tex``)."""
    from src.experiments.augment import TRANSFORMS

    for kind in ("mlp", "cnn"):
        path = Path(results_dir) / f"augmentation_{kind}.json"
        target = out_dir / f"augmentation_{kind}.tex"
        if not path.is_file():
            target.write_text(
                f"\\emph{{Chưa chạy thí nghiệm tăng cường dữ liệu cho {kind.upper()}.}}\n",
                encoding="utf-8",
            )
            continue
        r = json.loads(path.read_text(encoding="utf-8"))
        rows = []
        for key, c in r["conditions"].items():
            n = c["runs"][0]["n_train"]
            d = c.get("val_delta_vs_baseline_mean", 0.0)
            sd = c.get("val_delta_vs_baseline_sd", 0.0)
            rob = c["robust_test_acc_mean"]
            rows.append(
                f"{AUG_NAME.get(key, _tex(key))} & {f'{n:,}'.replace(',', chr(92) + ',')} & "
                + f"{_pct(c['val_acc_mean'])} $\\pm$ {_pct(c['val_acc_std'])} & "
                f"{100 * d:+.2f} $\\pm$ {100 * sd:.2f} & "
                f"{_pct(c['test_acc_mean'])} & "
                + " & ".join(_pct(rob[t], 1) for t in TRANSFORMS)
                + " \\\\"
            )
        seeds = ", ".join(str(s) for s in r["seeds"])
        tex = [
            r"\begin{table}[H]\centering\scriptsize",
            r"\setlength{\tabcolsep}{3pt}",
            r"\begin{tabular}{lrrrrrrrrr}",
            r"\toprule",
            r" & & \multicolumn{2}{c}{Validation} & Test & \multicolumn{5}{c}{Test sau nhiễu (\%)} \\",
            r"\cmidrule(lr){3-4}\cmidrule(lr){6-10}",
            r"Điều kiện & Số mẫu & Acc (\%) & $\Delta$ so với gốc & Acc (\%) & Xoay & Dịch & Co giãn & Gauss & Muối tiêu \\",
            r"\midrule",
            *rows,
            r"\bottomrule",
            r"\end{tabular}",
            f"\\caption{{{kind.upper()} với cấu hình đã chọn, huấn luyện lại với {len(r['seeds'])} seed ({seeds}) "
            f"cho mỗi điều kiện; $\\Delta$ là hiệu validation accuracy so với điều kiện gốc \\emph{{cùng seed}} "
            f"(trung bình $\\pm$ độ lệch chuẩn mẫu). {r['k_copies']} bản sao biến đổi cho mỗi ảnh train; điều kiện "
            f"được chọn chỉ theo validation (\\texttt{{{_tex(r['selected_by_validation'])}}}). Các cột ``Test sau nhiễu'' "
            f"đo độ bền trên tập test bị biến đổi ở mức mạnh hơn mức huấn luyện, chỉ để báo cáo.}}",
            f"\\label{{tab:augmentation-{kind}}}",
            r"\end{table}",
        ]
        target.write_text("\n".join(tex) + "\n", encoding="utf-8")


def write_confusions(data, out_dir):
    items = []
    for mid in ORDER:
        f = data[mid]["final"]
        if not f:
            continue
        top = top_confusions(f["splits"]["test"]["confusion_matrix"], k=3)
        txt = ", ".join(f"{t['true']}$\\to${t['pred']} ({t['count']})" for t in top)
        items.append(f"\\item[{_tex(TITLE[mid])}.] {txt}.")
    body = "\n".join(items)
    (out_dir / "confusions.tex").write_text(
        "\\begin{description}[leftmargin=0pt,labelindent=0pt,style=unboxed,itemsep=2pt]\n"
        + body
        + "\n\\end{description}\n",
        encoding="utf-8",
    )


def write_sweeps(data, out_dir):
    """One line per sweep: tested values and the validation accuracy range."""
    rows = []
    for mid in ORDER:
        t = data[mid]["tuning"]
        if not t:
            continue
        for param, trs in sweep_points(t).items():
            best = max(trs, key=lambda x: x["val_acc"])
            worst = min(trs, key=lambda x: x["val_acc"])
            rows.append(
                f"{_tex(TITLE[mid])} & \\texttt{{{_tex(param)}}} & {len(trs)} & "
                f"{_pct(worst['val_acc'])} & {_pct(best['val_acc'])} & "
                f"\\texttt{{{_tex(json.dumps(best['value']).replace('[', '(').replace(']', ')'))}}} \\\\"
            )
    tex = [
        r"\begin{tabular}{llrrrl}",
        r"\toprule",
        r"Mô hình & Siêu tham số & Số giá trị & Val thấp nhất & Val cao nhất & Giá trị tốt nhất \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
    ]
    (out_dir / "sweeps.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")


def write_fragments(results_dir, out_dir=None, artifacts_dir=ARTIFACTS_DIR, count_tests=True):
    out_dir = Path(out_dir or ROOT / "report" / "generated")
    out_dir.mkdir(parents=True, exist_ok=True)
    data = load_all(results_dir)
    write_numbers(data, out_dir)
    write_mcnemar(results_dir, out_dir)
    write_hardware(data, out_dir)
    if count_tests:
        write_ntests(out_dir)
    write_export_check(out_dir, artifacts_dir)
    write_augmentation(results_dir, out_dir)
    write_confusions(data, out_dir)
    write_sweeps(data, out_dir)
    return out_dir
